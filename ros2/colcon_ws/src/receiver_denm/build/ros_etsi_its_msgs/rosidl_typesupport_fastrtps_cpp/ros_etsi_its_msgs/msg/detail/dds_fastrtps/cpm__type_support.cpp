get_serialized_size_key(
  const ros_etsi_its_msgs::msg::CPM & ros_message,
  size_t current_alignment)
{
  size_t initial_alignment = current_alignment;

  const size_t padding = 4;
  const size_t wchar_size = 4;
  (void)padding;
  (void)wchar_size;

  // Member: header
  current_alignment +=
    std_msgs::msg::typesupport_fastrtps_cpp::get_serialized_size_key(
    ros_message.header, current_alignment);

  // Member: its_header
  current_alignment +=
    ros_etsi_its_msgs::msg::typesupport_fastrtps_cpp::get_serialized_size_key(
    ros_message.its_header, current_alignment);

  // Member: generation_delta_time
  {
    size_t item_size = sizeof(ros_message.generation_delta_time);
    current_alignment += item_size +
      eprosima::fastcdr::Cdr::alignment(current_alignment, item_size);
  }

  // Member: station_type
  current_alignment +=
    ros_etsi_its_msgs::msg::typesupport_fastrtps_cpp::get_serialized_size_key(
    ros_message.station_type, current_alignment);

  // Member: reference_position
  current_alignment +=
    ros_etsi_its_msgs::msg::typesupport_fastrtps_cpp::get_serialized_size_key(
    ros_message.reference_position, current_alignment);

  // Member: originating_vehicle_container
  current_alignment +=
    ros_etsi_its_msgs::msg::typesupport_fastrtps_cpp::get_serialized_size_key(
    ros_message.originating_vehicle_container, current_alignment);

  // Member: has_sensor_information_container
  {
    size_t item_size = sizeof(ros_message.has_sensor_information_container);
    current_alignment += item_size +
      eprosima::fastcdr::Cdr::alignment(current_alignment, item_size);
  }

  // Member: sensor_information_container
  current_alignment +=
    ros_etsi_its_msgs::msg::typesupport_fastrtps_cpp::get_serialized_size_key(
    ros_message.sensor_information_container, current_alignment);

  // Member: has_list_of_perceived_object
  {
    size_t item_size = sizeof(ros_message.has_list_of_perceived_object);
    current_alignment += item_size +
      eprosima::fastcdr::Cdr::alignment(current_alignment, item_size);
  }

  // Member: list_of_perceived_objects
  current_alignment +=
    ros_etsi_its_msgs::msg::typesupport_fastrtps_cpp::get_serialized_size_key(
    ros_message.list_of_perceived_objects, current_alignment);

  // Member: number_of_perceived_objects
  {
    size_t item_size = sizeof(ros_message.number_of_perceived_objects);
    current_alignment += item_size +
      eprosima::fastcdr::Cdr::alignment(current_alignment, item_size);
  }

  return current_alignment - initial_alignment;
}

