function create_timeout(object_dict, object, marker){

    var id_time_out = setTimeout(function() {
        marker.remove();
        delete object_dict[object.id]
    }, object.expiration_time * Math.pow(10, 3));

    return id_time_out;
}


function get_marker_design(object){

    switch (object.type) {
        case "PEDESTRIAN": //"VEHICLE", "TRUCK", "MOTORCYCLE", "PEDESTRIAN", "CYCLIST", "UNKNOWN"
            return {icon: PedestrianIcon};
        case "VEHICLE":
            if(need_heading(object)){
                return {icon: EgoCarIcon, rotationOrigin: '20px 13.3px', rotationAngle: 180.0 + object.heading.value / 10.0};
            }
            return CarIcon;
        case "TRUCK":
            if(need_heading(object)){
                return {icon: EgoCarIcon, rotationOrigin: '20px 13.3px', rotationAngle: 180.0 + object.heading.value / 10.0};
            }
            return {icon: TruckIcon};
        case "MOTORCYCLE":
            if(need_heading(object)){
                return {icon: EgoCarIcon, rotationOrigin: '20px 13.3px', rotationAngle: 180.0 + object.heading.value / 10.0};
            }
            return {icon: CarIcon};
        case "CYCLIST":
        if(need_heading(object)){
                return {icon: EgoBikecycleIcon, rotationOrigin: '20px 13.3px', rotationAngle: 180.0 + object.heading.value / 10.0};
            }
            return {icon: BicycleIcon};
        case "RSU":
                return {icon: RSUIcon};
        case "PDK":
            if(need_heading(object)){
                return {icon: EgoCarIcon, rotationOrigin: '20px 13.3px', rotationAngle: 180.0 + object.heading.value / 10.0};
            }
            return {icon: PDKIcon};
        case "Level0":
                return {icon: Level0Icon};
        case "Level1":
                return {icon: Level1Icon};
        case "Level2":
                return {icon: Level2Icon};
        case "Level3":
                return {icon: Level3Icon};
        case "UNKNOWN":
            return {icon: CarIcon};
        case "Accident":
                return {icon: AccidentIcon};
        case "Wrongway":
                return {icon: WrongwayIcon};
        case "Roadwork":
                return {icon: RoadworkIcon};
        case "BrokenVehicle":
                return {icon: BrokenVehicleIcon};
        case "Unknown1":
            return {icon: Unknown1Icon};
        default:
            return {icon: CarIcon};
    }
}

function need_heading(object){
    return ((object.source === "GPS" || object.source === "CAM" || object.source === "CPM-S") && object.type != "RSU" && object.type != "PDK" && object.type != "Level0" && object.type != "Level1" && object.type != "Level2" && object.type != "Level3" && object.type != "Accident" && object.type != "Wrongway" && object.type != "Roadwork" && object.type != "Unknown1" && object.type != "BrokenVehicle" && object.type != "PEDESTRIAN"); //Change to CAM when marker is appropriated
}

function create_popup(object){
    var string = 'Type: ' + object.type;
    string = string + '<br>Source: ' + object.source;
    string = string + '<br>Source Id: ' + object.source_id;
    string = string + '<br>Expiration time: ' + object.expiration_time + 's';
    //string = string + '<img src="img/HMI/AEVW5_320_180.png" alt="Test">';

    return string;
}
